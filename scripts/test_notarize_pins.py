#!/usr/bin/env python3
"""The release build must compile against the committed dependency pins.

`notarize.sh` builds the app that is signed and shipped. Its project is
generated by XcodeGen into a gitignored directory, so it starts with no
`Package.resolved` and Xcode would resolve Sparkle, swift-subprocess and
swift-system from their (movable) tags. The script therefore has to install
`App/Package.resolved` into the generated project and pass
`-onlyUsePackageVersionsFromResolvedFile`. Run by `make test-scripts`.

    python3 scripts/test_notarize_pins.py

The real script runs in a temp checkout with `xcodegen`, `xcodebuild` and
`xcrun` stubbed, so nothing builds, signs or reaches the keychain. It stops at
"build produced no app", which is after the step under test.
"""

import os
import pathlib
import shutil
import subprocess
import tempfile
import unittest

SCRIPT = pathlib.Path(__file__).resolve().parent / "notarize.sh"
PINS = '{"pins": [], "version": 3}\n'


class NotarizePins(unittest.TestCase):
    def setUp(self):
        self.tmp = pathlib.Path(tempfile.mkdtemp(prefix="duo-notarize-pins-"))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.repo = self.tmp / "repo"
        (self.repo / "scripts").mkdir(parents=True)
        (self.repo / "App").mkdir()
        shutil.copy(SCRIPT, self.repo / "scripts" / "notarize.sh")
        self.pins = self.repo / "App" / "Package.resolved"
        self.pins.write_text(PINS)
        self.bin = self.tmp / "bin"
        self.bin.mkdir()
        self.log = self.tmp / "calls.log"
        self.stub("xcodegen", 'mkdir -p DuoUpdater.xcodeproj')
        self.stub("xcodebuild",
                  f'printf "%s\\n" "$*" >> "{self.log}"')
        self.stub("xcrun", "exit 0")

    def stub(self, name, body):
        path = self.bin / name
        path.write_text("#!/bin/sh\n" + body + "\n")
        path.chmod(0o755)

    def run_script(self):
        env = dict(os.environ)
        env["PATH"] = f"{self.bin}:/usr/bin:/bin"
        env["NOTARYTOOL_PROFILE"] = "x"
        env["DERIVED_DATA"] = str(self.tmp / "dd")
        env["DIST_DIR"] = str(self.tmp / "dist")
        env["FINAL_ZIP"] = str(self.tmp / "dist" / "final.zip")
        for k in ("NOTARY_PROFILE", "DUO_TEAM_ID"):
            env.pop(k, None)
        return subprocess.run(["bash", str(self.repo / "scripts" / "notarize.sh")],
                              env=env, capture_output=True, text=True)

    def calls(self):
        return self.log.read_text() if self.log.exists() else ""

    # Mutation: drop `-onlyUsePackageVersionsFromResolvedFile` from the Release
    # xcodebuild and this fails; drop the `cp` and the content check fails.
    def test_the_release_build_is_confined_to_the_committed_pins(self):
        run = self.run_script()
        # Stops after the build step: the stub produces no app.
        self.assertIn("build produced no app", run.stderr)
        self.assertIn("-onlyUsePackageVersionsFromResolvedFile", self.calls())
        self.assertIn("build", self.calls().split())
        installed = (self.repo / "App" / "DuoUpdater.xcodeproj" / "project.xcworkspace"
                     / "xcshareddata" / "swiftpm" / "Package.resolved")
        self.assertEqual(installed.read_text(), PINS)

    # Mutation: drop the existence check and a missing pin file turns back into
    # a live resolve of every dependency, with the signing identity in reach.
    def test_a_missing_pin_file_is_refused_before_building(self):
        self.pins.unlink()
        run = self.run_script()
        self.assertNotEqual(run.returncode, 0)
        self.assertIn("App/Package.resolved is missing", run.stderr)
        self.assertEqual(self.calls(), "", "xcodebuild ran without pins")


if __name__ == "__main__":
    unittest.main(verbosity=2)
