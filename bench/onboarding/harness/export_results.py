"""Write results/runs.yml from the work directory: one record per finished run.

Reads $BENCH_ROOT/scores.json (run.sh score), $BENCH_ROOT/probe.txt (run.sh probe) and
each run's t0 and costs.json. Run tags name the configuration: <model>[-<effort>][-b2]
for a single agent, pipe<A|B>-<repetition> for a pipeline.
"""
import datetime, json, os, re

B = os.environ.get("BENCH_ROOT") or os.path.expanduser("~/duo-updater-bench")
H = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(H), "results", "runs.yml")
SIMPLE9 = {"rustgis", "plexo", "pulse", "search", "herdr", "reviu", "aircard", "astrlink", "yomado"}
M = {"haiku": "claude-haiku-5-5", "sonnet": "claude-sonnet-5-5", "opus": "claude-opus-5-5"}


def config(tag):
    if tag.startswith("pipe"):
        group, rep = tag[4], tag.split("-")[1]
        stages = [{"stage": "plan", "model": M["opus"], "effort": "high"}] if group == "B" else []
        stages += [
            {"stage": "exec", "model": M["sonnet"], "effort": "high",
             "subagent": {"model": M["haiku"], "effort": "xhigh"}},
            {"stage": "review", "model": M["opus"], "effort": "high"},
            {"stage": "fix", "model": M["sonnet"], "effort": "high", "resumes": "exec"},
        ]
        # repetition 2 onward ran with DITTO_NOTE=1
        return {"mode": "pipeline-" + group, "repetition": int(rep), "stages": stages,
                "brief": "brief.md" + (" + ditto-note.md" if int(rep) >= 2 else "")}
    p = tag.split("-")
    effort = p[1] if len(p) > 1 and p[1] in ("low", "medium", "high", "xhigh", "max") else "high"
    return {"mode": "single", "model": M.get(p[0], p[0]), "effort": effort,
            "brief": "brief2.md" if tag.endswith("-b2") else "brief.md"}


def round_of(tag, case):
    if tag in ("haiku", "sonnet", "opus"):
        return 1
    if tag == "haiku-max" or (tag == "haiku-xhigh" and case in SIMPLE9):
        return 2
    if tag == "haiku-xhigh":
        return 3
    if tag in ("haiku-xhigh-b2", "opus-xhigh", "sonnet-xhigh"):
        return 4
    return 5


def q(v):
    return "null" if v is None else (str(v) if isinstance(v, (int, float)) else json.dumps(str(v), ensure_ascii=False))


rows = json.load(open(os.path.join(B, "scores.json")))
probe = {}
if os.path.exists(os.path.join(B, "probe.txt")):
    for line in open(os.path.join(B, "probe.txt")):
        m = re.match(r"^(\S+)\s+(.*?) \| tags", line)
        if m:
            probe[m.group(1)] = m.group(2)

out = ["# Every onboarding run, one record each. Generated by harness/export_results.py from",
       "# harness/score.py and harness/probe.py output (see README.md). `vs_main` compares the",
       "# graded behaviour with main's as last re-graded: an older run can show a DIFF only",
       "# because the vendor released since. `probe` runs the stable rule's version pattern",
       "# on synthetic next tags (NEXT-MISS, SUFFIX-AS-STABLE).",
       'environment: {claude_code: "2.1.296", macos: "27.2", swift: "6.4"}', "runs:"]
for r in sorted(rows, key=lambda r: (round_of(r["model"], r["case"]), r["model"], r["case"])):
    tag, case = r["model"], r["case"]
    d = os.path.join(B, "runs", case + "-" + tag)
    t0 = int(open(d + "/t0").read())
    verdict = "LIVE" if not r["has_ref"] else ("MATCH" if not r["diffs"] else "DIFF(%d)" % len(r["diffs"]))
    out += ["  - run: " + q(case + "-" + tag),
            "    round: %d" % round_of(tag, case),
            "    date: " + q(datetime.datetime.fromtimestamp(t0).strftime("%Y-%m-%d")),
            "    case: " + q(case),
            "    config: " + json.dumps(config(tag), ensure_ascii=False),
            "    cost_usd: %s" % r["cost"]]
    if os.path.exists(d + "/costs.json"):
        stages = {s: {"usd": v["total"], "minutes": v["minutes"], "by_model": v["by_model"]}
                  for s, v in json.load(open(d + "/costs.json")).items()}
        out.append("    cost_by_stage: " + json.dumps(stages))
    out += ["    minutes: %s" % r["minutes"],
            "    turns: " + q(r["turns"]),
            "    make_test_rc: " + q(r["make_test"]),
            "    vs_main: " + q(verdict),
            "    probe: " + q(probe.get(case + "-" + tag)),
            "    head: " + q(r["head"])]
open(OUT, "w").write("\n".join(out) + "\n")
print("%d runs -> %s" % (len(rows), OUT))
